#!/bin/bash
# =============================================================
# CastPanel - DJ Control Center on port 2080
# =============================================================
# Serves the DJ portal (PANEL_DIR/dj) on its own port so DJs log in at
#   http(s)://your-domain:2080
#
# Safe to run on an existing, working server (and to run again):
#   - only adds its own Apache file (castpanel-dj.conf)
#   - checks the Apache config before reloading; if the check fails the
#     file is removed again, so the running panel is never taken down
#
# Usage (as root):
#   bash install/setup_dj_port.sh [PANEL_DIR] [DOMAIN]
#   PANEL_DIR defaults to /var/www/castpanel
#   DOMAIN    defaults to SSL_DOMAIN from PANEL_DIR/config/database.php
# =============================================================

DJ_PORT="${DJ_PORT:-2080}"
PANEL_DIR="${1:-/var/www/castpanel}"
DOMAIN="${2:-}"

ok()   { echo "  [OK]    $1"; }
info() { echo "  [INFO]  $1"; }
warn() { echo "  [!]     $1"; }
fail() { echo "  [ERROR] $1"; exit 1; }

[ -d "$PANEL_DIR/dj" ] || fail "DJ portal not found: $PANEL_DIR/dj"

if [ -z "$DOMAIN" ] && [ -f "$PANEL_DIR/config/database.php" ]; then
    DOMAIN=$(grep -oP "define\('SSL_DOMAIN',\s*'\K[^']+" "$PANEL_DIR/config/database.php" 2>/dev/null)
fi
case "$DOMAIN" in __*|"") DOMAIN="" ;; esac

# ---- Apache layout (Debian/Ubuntu vs RHEL/AlmaLinux/Rocky) ----
if [ -d /etc/apache2 ]; then
    FLAVOR="debian"
    CONF_FILE="/etc/apache2/sites-available/castpanel-dj.conf"
    APACHE_CONF_ROOT="/etc/apache2"
    LOG_DIR="/var/log/apache2"
    SERVICE="apache2"
elif [ -d /etc/httpd ]; then
    FLAVOR="rhel"
    CONF_FILE="/etc/httpd/conf.d/castpanel-dj.conf"
    APACHE_CONF_ROOT="/etc/httpd"
    LOG_DIR="/var/log/httpd"
    SERVICE="httpd"
else
    fail "Apache not found (/etc/apache2 or /etc/httpd)"
fi

if command -v apache2ctl >/dev/null 2>&1; then APACHECTL="apache2ctl"; else APACHECTL="apachectl"; fi

# ---- SSL: use the panel's Let's Encrypt certificate when there is one ----
SSL_BLOCK=""
CERT_DIR="/etc/letsencrypt/live/$DOMAIN"
if [ -n "$DOMAIN" ] && [ -f "$CERT_DIR/fullchain.pem" ] && [ -f "$CERT_DIR/privkey.pem" ]; then
    [ "$FLAVOR" = "debian" ] && a2enmod ssl >/dev/null 2>&1
    SSL_BLOCK="    SSLEngine on
    SSLCertificateFile $CERT_DIR/fullchain.pem
    SSLCertificateKeyFile $CERT_DIR/privkey.pem"
    SCHEME="https"
else
    SCHEME="http"
fi

# Only declare "Listen" if no other Apache file already does it
LISTEN_LINE="Listen $DJ_PORT"
if grep -rqsE "^\s*Listen\s+([0-9.:\[\]]*:)?$DJ_PORT(\s|$)" "$APACHE_CONF_ROOT" --exclude="castpanel-dj.conf"; then
    LISTEN_LINE="# Listen $DJ_PORT is already declared elsewhere"
fi

# Keep a copy of a previous version so it can be restored if the new one fails
BACKUP=""
[ -f "$CONF_FILE" ] && BACKUP="$CONF_FILE.bak" && cp "$CONF_FILE" "$BACKUP"

cat > "$CONF_FILE" <<CONFEOF
# CastPanel - DJ Control Center (generated by install/setup_dj_port.sh)
$LISTEN_LINE

<VirtualHost *:$DJ_PORT>
${DOMAIN:+    ServerName $DOMAIN}
    DocumentRoot $PANEL_DIR/dj
    DirectoryIndex index.php
$SSL_BLOCK

    <Directory $PANEL_DIR/dj>
        AllowOverride None
        Require all granted
        Options -Indexes +FollowSymLinks
    </Directory>

    # Layout files are only included by PHP, never requested directly
    <Directory $PANEL_DIR/dj/includes>
        Require all denied
    </Directory>

    # Profile photos: never execute anything uploaded here
    <Directory $PANEL_DIR/dj/uploads>
        <FilesMatch "\.(php|phtml|phar|php[0-9]|pht|cgi|pl|py|sh)\$">
            Require all denied
        </FilesMatch>
        <IfModule mod_php.c>
            php_admin_flag engine off
        </IfModule>
        <IfModule mod_php7.c>
            php_admin_flag engine off
        </IfModule>
    </Directory>

    ErrorLog $LOG_DIR/castpanel_dj_error.log
    CustomLog $LOG_DIR/castpanel_dj_access.log combined
</VirtualHost>
CONFEOF
ok "Apache config written: $CONF_FILE ($SCHEME on port $DJ_PORT)"

[ "$FLAVOR" = "debian" ] && a2ensite castpanel-dj.conf >/dev/null 2>&1

# ---- Never leave Apache broken: test before reloading ----
if ! $APACHECTL configtest >/dev/null 2>&1; then
    warn "Apache config test failed:"
    $APACHECTL configtest 2>&1 | sed 's/^/          /'
    [ "$FLAVOR" = "debian" ] && a2dissite castpanel-dj.conf >/dev/null 2>&1
    if [ -n "$BACKUP" ]; then mv "$BACKUP" "$CONF_FILE"; else rm -f "$CONF_FILE"; fi
    fail "Change reverted, Apache was not touched."
fi
rm -f "$BACKUP"
ok "Apache config test passed"

# ---- SELinux (RHEL): allow Apache to listen on the port ----
if command -v semanage >/dev/null 2>&1 && command -v getenforce >/dev/null 2>&1 && [ "$(getenforce)" != "Disabled" ]; then
    semanage port -a -t http_port_t -p tcp "$DJ_PORT" 2>/dev/null \
        || semanage port -m -t http_port_t -p tcp "$DJ_PORT" 2>/dev/null
    ok "SELinux: port $DJ_PORT allowed for Apache"
fi

# ---- Firewall ----
if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
    firewall-cmd --permanent --add-port="$DJ_PORT/tcp" >/dev/null 2>&1
    firewall-cmd --reload >/dev/null 2>&1
    ok "firewalld: port $DJ_PORT/tcp open"
elif command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
    ufw allow "$DJ_PORT/tcp" >/dev/null 2>&1
    ok "ufw: port $DJ_PORT/tcp open"
else
    info "No active firewall found (open $DJ_PORT/tcp in your provider's firewall if it has one)"
fi

# ---- Reload Apache (graceful: open connections are not dropped) ----
if command -v systemctl >/dev/null 2>&1 && systemctl is-active --quiet "$SERVICE" 2>/dev/null; then
    systemctl reload "$SERVICE" && ok "Apache reloaded"
elif pgrep -x apache2 >/dev/null 2>&1 || pgrep -x httpd >/dev/null 2>&1; then
    $APACHECTL graceful && ok "Apache reloaded"
else
    info "Apache is not running; the port will be active when it starts"
fi

echo ""
echo "  DJ Control Center: $SCHEME://${DOMAIN:-SERVER_IP}:$DJ_PORT"
